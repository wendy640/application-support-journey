## 🧠 Reflection

Today's lesson shifted my perspective from retrieving raw records to generating meaningful insights.

Aggregate functions answer business questions such as:

- How many customers do we have?
- What is the average product price?
- What is the total salary expense?
- Which product is the cheapest?
- Which product is the most expensive?

These are common reporting tasks performed by database administrators, analysts, and Application Support Engineers.

