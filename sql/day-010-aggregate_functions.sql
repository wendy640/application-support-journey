# 📅 Day 10 – Aggregate Functions in PostgreSQL

Today, I learned how to summarize and analyze data using SQL Aggregate Functions. Instead of retrieving every row individually, aggregate functions allow us to generate meaningful insights from a dataset.

---

## 📚 Topics Covered

- `COUNT()`
- `COUNT(column)`
- `COUNT(DISTINCT column)`
- `SUM()`
- `AVG()`
- `ROUND()`
- `MIN()`
- `MAX()`
- Combining Multiple Aggregate Functions

---

## 🎯 Key Takeaways

- Used `COUNT()` to determine the number of records.
- Learned the difference between `COUNT(*)` and `COUNT(column)`.
- Used `COUNT(DISTINCT column)` to count unique values.
- Calculated totals using `SUM()`.
- Computed averages with `AVG()`.
- Rounded decimal values using `ROUND()`.
- Retrieved the smallest and largest values using `MIN()` and `MAX()`.
- Combined multiple aggregate functions into a single business summary report.

